"""
alpha_engine.engine.strategy.base — Institutional Base Strategy Architecture
===========================================================================
Defines the unified abstract base class, signal data structures, exit signals,
market regime enumerations, and Fractional Kelly sizing math for all quantitative strategies.
"""

from __future__ import annotations

import math
import time
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from decimal import Decimal
from enum import Enum
from typing import Any, Optional

from alpha_engine.models.enums import (
    ChainIdentifier,
    ExitProfile,
    OrderSide,
    SignalStrength,
    StrategyType,
    TradeExitReason,
)
from alpha_engine.models.state import PoolState, SecurityReport


class MarketRegime(str, Enum):
    """Market regime classification for adaptive strategy routing."""
    TRENDING_BULL = "trending_bull"
    TRENDING_BEAR = "trending_bear"
    RANGING_SIDEWAYS = "ranging_sideways"
    HIGH_VOLATILITY_BURST = "high_volatility_burst"
    LIQUIDITY_EXPANSION = "liquidity_expansion"
    UNKNOWN = "unknown"


@dataclass
class StrategySignal:
    """Standardized institutional signal generated by any strategy."""
    token_address: str
    chain: ChainIdentifier
    strategy_type: StrategyType
    side: OrderSide = OrderSide.BUY
    confidence: float = 0.80                # 0.0 to 1.0
    entry_price: Decimal = Decimal("0")
    expected_slippage_bps: int = 150
    stop_loss_pct: float = -12.0             # Negative percentage (e.g. -12.0 = -12%)
    take_profit_ladder: list[dict[str, float]] = field(default_factory=lambda: [
        {"trigger_multiplier": 1.30, "sell_pct": 50.0},
        {"trigger_multiplier": 1.70, "sell_pct": 50.0},
    ])
    trailing_stop_pct: float = 20.0         # Drawdown from peak to trigger trailing stop
    trailing_activation_pct: float = 25.0    # Minimum profit % before trailing stop activates
    max_hold_seconds: float = 1800.0         # Time-based expiration in seconds
    kelly_fraction: float = 0.5              # Half-Kelly multiplier (0.25 to 1.0)
    recommended_position_pct: float = 1.0    # % of available portfolio capital (0.25% - 2.5%)
    rationale: str = ""
    indicators: dict[str, Any] = field(default_factory=dict)
    exit_profile: ExitProfile = ExitProfile.FAST_SNIPE
    strength: SignalStrength = SignalStrength.MODERATE
    timestamp: float = field(default_factory=time.time)

    def to_dict(self) -> dict[str, Any]:
        return {
            "token_address": self.token_address,
            "chain": self.chain.value if hasattr(self.chain, "value") else str(self.chain),
            "strategy_type": self.strategy_type.value if hasattr(self.strategy_type, "value") else str(self.strategy_type),
            "side": self.side.value if hasattr(self.side, "value") else str(self.side),
            "confidence": self.confidence,
            "entry_price": str(self.entry_price),
            "expected_slippage_bps": self.expected_slippage_bps,
            "stop_loss_pct": self.stop_loss_pct,
            "take_profit_ladder": self.take_profit_ladder,
            "trailing_stop_pct": self.trailing_stop_pct,
            "trailing_activation_pct": self.trailing_activation_pct,
            "max_hold_seconds": self.max_hold_seconds,
            "kelly_fraction": self.kelly_fraction,
            "recommended_position_pct": self.recommended_position_pct,
            "rationale": self.rationale,
            "indicators": self.indicators,
            "exit_profile": self.exit_profile.value if hasattr(self.exit_profile, "value") else str(self.exit_profile),
            "strength": self.strength.value if hasattr(self.strength, "value") else str(self.strength),
            "timestamp": self.timestamp,
        }


@dataclass
class StrategyExitSignal:
    """Decision output when evaluating position exit conditions."""
    should_exit: bool
    exit_ratio: float = 1.0                  # 1.0 = close 100%, 0.5 = partial 50%
    reason: TradeExitReason = TradeExitReason.MANUAL_CLOSE
    rationale: str = ""
    target_price: Decimal = Decimal("0")
    stage_index: int = 0                     # Ladder index if staged TP


class BaseStrategy(ABC):
    """
    Abstract Base Class for all institutional Bot-MM trading strategies.
    Enforces unified interfaces for entry evaluation, exit evaluation,
    dynamic position sizing via Fractional Kelly, and runtime hyperparameter adaptation.
    """

    def __init__(
        self,
        strategy_type: StrategyType,
        name: str,
        enabled: bool = True,
        weight: float = 1.0,
    ) -> None:
        self.strategy_type = strategy_type
        self.name = name
        self.enabled = enabled
        self.weight = weight
        self._hyperparameters: dict[str, Any] = {}
        self.suitable_regimes: list[MarketRegime] = [MarketRegime.TRENDING_BULL, MarketRegime.RANGING_SIDEWAYS]

    @abstractmethod
    def evaluate_entry(
        self,
        token_address: str,
        chain: ChainIdentifier,
        current_price: Decimal,
        pool_state: Optional[PoolState] = None,
        security_report: Optional[SecurityReport] = None,
        staged_data: Optional[Any] = None,
        market_data: Optional[dict[str, Any]] = None,
    ) -> Optional[StrategySignal]:
        """
        Evaluate entry conditions for a token.
        Returns a StrategySignal if entry conditions are met, otherwise None.
        """
        pass

    @abstractmethod
    def evaluate_exit(
        self,
        position: Any,
        current_price: Decimal,
        peak_price: Decimal,
        elapsed_seconds: float,
        pool_state: Optional[PoolState] = None,
    ) -> StrategyExitSignal:
        """
        Evaluate multi-condition exit rules (Staggered TP, Dynamic Trailing Stop,
        Time-Based Invalidation, and Risk-Based Stop Loss).
        """
        pass

    def calculate_fractional_kelly_size(
        self,
        win_rate_pct: float = 55.0,
        win_loss_payoff_ratio: float = 1.8,
        fraction: float = 0.5,
        confidence_multiplier: float = 1.0,
        min_size_pct: float = 0.35,
        max_size_pct: float = 2.50,
    ) -> float:
        """
        Calculate dynamic position size as a percentage of total portfolio capital
        using the Kelly Criterion with fractional dampening.
        Kelly Formula: f* = (p * b - q) / b
          p = win probability
          q = loss probability (1 - p)
          b = win/loss payoff ratio (average win / average loss)
        """
        p = max(0.20, min(0.95, win_rate_pct / 100.0))
        q = 1.0 - p
        b = max(0.5, win_loss_payoff_ratio)

        raw_kelly = (p * b - q) / b
        if not math.isfinite(raw_kelly) or raw_kelly <= 0:
            return min_size_pct

        # Apply fractional dampening (e.g. half-kelly = 0.5) and confidence scaling
        dampened = raw_kelly * fraction * confidence_multiplier * 10.0
        return round(max(min_size_pct, min(max_size_pct, dampened)), 2)

    def update_hyperparameters(self, params: dict[str, Any]) -> None:
        """Update runtime hyperparameters dynamically from the self-learning tuner."""
        for k, v in params.items():
            if k in self._hyperparameters:
                self._hyperparameters[k] = v

    def get_hyperparameters(self) -> dict[str, Any]:
        """Retrieve current active hyperparameters."""
        return dict(self._hyperparameters)

    def set_enabled(self, enabled: bool) -> None:
        self.enabled = enabled

    def set_weight(self, weight: float) -> None:
        self.weight = max(0.0, min(3.0, weight))
